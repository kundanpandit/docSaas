package com.docsaas.api.model;

import java.time.LocalDateTime;

import org.springframework.data.annotation.Id;
import org.springframework.data.relational.core.mapping.Table;

import lombok.Data;

@Data
@Table("job_files")
public class JobFile {

    public static final String ROLE_INPUT = "INPUT";
    public static final String ROLE_OUTPUT = "OUTPUT";
    /** JSON data part sent with the job (see ToolProcessor.maxDataBytes). */
    public static final String ROLE_DATA = "DATA";

    @Id
    private Long id;

    private Long jobId;
    private String role;
    private Integer sortOrder;
    /** Path relative to the storage root; generated by the server, never from user input. */
    private String storageKey;
    private String originalName;
    private String mimeType;
    private Long sizeBytes;
    private LocalDateTime createdAt;
}
